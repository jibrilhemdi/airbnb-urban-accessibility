"""Render manuscript tables from checksum-pinned, final aggregate exports.

No database writes, model fitting or row-level exports. Additional descriptive
means are computed from verified frozen PostGIS samples, without refitting.
Run from any directory; --check verifies the committed presentation artifacts.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "thesis_report/tables"
CATALOG = ROOT / "reports/thesis_artifact_manifest.json"
CATALOG_SHA256 = "29bf5b8334080cd4e8050a2d86dd415927aa3f051b38b7d9583996be3e007a52"
CITIES = ("Copenhagen", "Oslo", "Stockholm")
ESTIMATORS = ("OLS", "XGBoost")
MODELS = ("M0", "ME", "MW", "MEW")
MODEL_TEX = dict(zip(MODELS, (r"$M_0$", r"$M_E$", r"$M_W$", r"$M_{EW}$")))


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def one(rows: list[dict], **keys: str) -> dict:
    selected = [row for row in rows if all(row[key] == value for key, value in keys.items())]
    if len(selected) != 1:
        raise ValueError(f"Expected one aggregate row for {keys}; found {len(selected)}")
    return selected[0]


def number(value: str | float, places: int = 4, signed: bool = False) -> str:
    value = float(value)
    if not math.isfinite(value):
        raise ValueError("Missing/nonfinite aggregate cannot be filled")
    return f"{value:+.{places}f}" if signed else f"{value:.{places}f}"


def table(name: str, caption: str, columns: str, header: str,
          body: list[str], note: str, sources: list[str], inputs: dict) -> str:
    provenance = "\n".join(f"% Source: {path}; SHA256: {inputs[path]['sha256']}" for path in sources)
    return "\n".join([
        "% Generated by scripts/build_thesis_chapter_tables.py; do not edit numbers.",
        provenance, r"\begin{table}[H]", r"\centering", r"\small",
        r"\caption{" + caption + "}", r"\label{tab:" + name + "}",
        r"\begin{tabular}{" + columns + "}", r"\toprule", header + r" \\",
        r"\midrule", *body, r"\bottomrule", r"\end{tabular}",
        r"\par\smallskip", r"\begin{minipage}{\textwidth}\footnotesize",
        note, r"\end{minipage}", r"\end{table}", "",
    ])


def render() -> dict[str, str]:
    if digest(CATALOG.read_bytes()) != CATALOG_SHA256:
        raise ValueError("Final aggregate catalog changed; review evidence before updating its pin")
    catalog = json.loads(CATALOG.read_text())
    registered = {item["filename"]: item for item in catalog["items"]}
    inputs = {}

    def read(path: str) -> list[dict]:
        item = registered[path]
        raw = (ROOT / path).read_bytes()
        if digest(raw) != item["sha256"]:
            raise ValueError(f"Frozen aggregate checksum mismatch: {path}")
        inputs[path] = {"sha256": item["sha256"], "source_run_artifact": item["source_run_artifact"]}
        return list(csv.DictReader(raw.decode().splitlines()))

    paths = {name: f"outputs/tables/{name}.csv" for name in (
        "city_sample_summary", "accessibility_descriptive_statistics",
        "primary_predictive_performance", "paired_model_contrasts",
        "association_results", "validation_comparison", "transfer_performance",
        "transfer_contrasts", "robustness_registry")}
    paths.update({name: f"outputs/metrics/{name}.csv" for name in (
        "neighbourhood_performance", "robustness_contrasts", "residual_spatial_diagnostics")})
    data = {name: read(path) for name, path in paths.items()}
    from thesis_accessibility_summary import summarise
    accessibility_summary, summary_provenance = summarise(data["accessibility_descriptive_statistics"])
    outputs = {}

    def emit(name, caption, columns, header, body, note, source_names):
        outputs[name + ".tex"] = table(name, caption, columns, header, body, note,
                                        [paths[key] for key in source_names], inputs)

    body = []
    for city in CITIES:
        for concept, label, places in (("station", "Rail distance (km)", 3),
                                      ("bus", "Bus distance (km)", 3),
                                      ("food", "Food/social destinations", 0),
                                      ("culture", "Culture/tourism destinations", 0)):
            values = []
            for rep in ("Euclidean", "Walking"):
                row = accessibility_summary[f"{city}:{concept}:{rep}"]
                values.extend([number(row["median"], places), number(row["mean"], places if places else 1)])
            body.append(" & ".join([city if concept == "station" else "", label,
                                    *values]) + r" \\")
        if city != CITIES[-1]: body.append(r"\addlinespace")
    emit("accessibility", "Median and mean accessibility on the common predictive samples.",
         "llrrrr", r" & & \multicolumn{2}{c}{Euclidean} & \multicolumn{2}{c}{Walking} \\ "
         r"\cmidrule(lr){3-4}\cmidrule(lr){5-6} City & Measure & Median & Mean & Median & Mean", body,
         "Distances refer to the nearest destination within each matched category. "
         "Walking distances are converted from saved walking times at 5 km/h for this "
         "display; the models retain walking minutes. Opportunity counts use 833 m "
         "and 10 minutes, respectively. Means average original distances and counts. "
         "Nearest destinations may differ between representations.",
         ["accessibility_descriptive_statistics"])
    outputs["accessibility.tex"] = (
        "% Additional means source: read-only study.records prediction_sample; "
        "frozen selection config/study/sample_selection.json; "
        "sample/code hashes in tables/manifest.json.\n" + outputs["accessibility.tex"])

    body = []
    for city in CITIES:
        for estimator in ESTIMATORS:
            rows = [one(data["primary_predictive_performance"], city=city,
                        estimator=estimator, model=model) for model in MODELS]
            expected = int(one(data["city_sample_summary"], city=city)["prediction_n"])
            if any(int(row["n"]) != expected for row in rows):
                raise ValueError("Model samples differ")
            body.append(" & ".join([city, estimator, *(number(r["rmse"]) for r in rows)]) + r" \\")
        if city != CITIES[-1]: body.append(r"\addlinespace")
    emit("primary", "Within-city RMSE under neighbourhood holdouts.", "llrrrr",
         "City & Estimator & " + " & ".join(MODEL_TEX.values()), body,
         r"RMSE is measured in natural-log asking-price units; lower is better. "
         r"$M_0$: controls; $M_E$: controls plus Euclidean accessibility; "
         r"$M_W$: controls plus walking accessibility; $M_{EW}$: controls plus both. "
         "Each city uses identical observations and folds across the four models.",
         ["primary_predictive_performance", "city_sample_summary"])

    body = []
    for city in CITIES:
        for model in MODELS[1:]:
            row = one(data["paired_model_contrasts"], city=city, estimator="XGBoost",
                      added=model, reference="M0")
            body.append(" & ".join([city, MODEL_TEX[model], number(row["delta_rmse"], 5, True),
                                    number(100 * float(row["proportional_change"]), 2, True),
                                    "[" + number(row["stability_low"], 5, True) + ", " +
                                    number(row["stability_high"], 5, True) + "]"]) + r" \\")
        if city != CITIES[-1]: body.append(r"\addlinespace")
    emit("gains", "XGBoost accessibility contributions relative to the control model.",
         "llrrl", r"City & Model & $\Delta$RMSE & Change (\%) & 95\% stability range", body,
         "Negative changes indicate lower error. Ranges resample neighbourhood "
         "composition conditional on the saved predictions (2,000 replications); "
         "they are not independent-sample confidence intervals or equivalence tests.",
         ["paired_model_contrasts"])

    body = []
    terms = (("nearest_station_euclidean_km", "Rail E (km)"),
             ("nearest_bus_euclidean_km", "Bus E (km)"),
             ("log1p_food_e", r"Food E ($\log(1+n)$)"),
             ("log1p_culture_e", r"Culture E ($\log(1+n)$)"),
             ("nearest_station_walking_minutes", "Rail W (min)"),
             ("nearest_bus_walking_minutes", "Bus W (min)"),
             ("log1p_food_w", r"Food W ($\log(1+n)$)"),
             ("log1p_culture_w", r"Culture W ($\log(1+n)$)"))
    for term, label in terms:
        values = []
        for city in CITIES:
            row = one(data["association_results"], city=city, model="MEW", term=term)
            values += [number(row["coefficient"]), number(row["wild_cluster_p_value"], 3)]
        body.append(" & ".join([label, *values]) + r" \\")
    emit("associations", "Adjusted accessibility associations in the joint complete-case model.",
         "lrrrrrr", r" & \multicolumn{2}{c}{Copenhagen} & \multicolumn{2}{c}{Oslo} & "
         r"\multicolumn{2}{c}{Stockholm} \\ Predictor & $\beta$ & $p_W$ & $\beta$ & $p_W$ & $\beta$ & $p_W$",
         body, r"Coefficients are conditional on all $X+E+W$ predictors. "
         r"$p_W$ is the unadjusted restricted Webb wild-cluster $p$-value "
         "(9,999 replications); these are individual coefficient tests, not a "
         "multiplicity-adjusted discovery procedure. E and W use the units shown, "
         "so coefficient magnitudes are not importance rankings. Complete-case "
         r"$N$: 12,285, 8,152 and 2,348; no missing bedrooms or outcomes are filled.",
         ["association_results"])

    body = []
    for city in CITIES:
        for estimator in ESTIMATORS:
            rows = [r for r in data["validation_comparison"]
                    if r["city"] == city and r["estimator"] == estimator]
            random = one(rows, model="M0", scheme="Random")
            primary = one(rows, model="M0", scheme="Neighbourhood")
            grids = sorted({r["scheme"] for r in rows} - {"Random", "Neighbourhood"})
            if len(grids) != 6: raise ValueError("Expected the six frozen grid configurations")
            blocks = sum(float(one(rows, model="MW", scheme=g)["rmse"]) <
                         float(one(rows, model="M0", scheme=g)["rmse"]) for g in grids)
            local = [r for r in data["neighbourhood_performance"]
                     if r["city"] == city and r["estimator"] == estimator]
            folds = sorted({r["fold"] for r in local})
            neighbourhoods = sum(float(one(local, fold=f, model="MW")["rmse"]) <
                                 float(one(local, fold=f, model="M0")["rmse"]) for f in folds)
            body.append(" & ".join([city, estimator, number(random["rmse"]), number(primary["rmse"]),
                                    f"{blocks}/6", f"{neighbourhoods}/{len(folds)}"]) + r" \\")
        if city != CITIES[-1]: body.append(r"\addlinespace")
    emit("geography", "Validation geography and the distribution of walking-model gains.",
         "llrrrr", r" & & \multicolumn{2}{c}{$M_0$ RMSE} & \multicolumn{2}{c}{$M_W$ beats $M_0$} "
         r"\\ City & Estimator & Random & Neigh. & Grids & Neigh.", body,
         "Grid counts cover 1, 1.5 and 2 km blocks, each with zero and half-block "
         "origins. Neighbourhood counts compare errors within each primary holdout. "
         "Counts use full-precision scores and describe correlated evaluation "
         "tasks; neither column counts independent replications. Pooled RMSE is "
         "not the unweighted mean of neighbourhood RMSEs.",
         ["validation_comparison", "neighbourhood_performance"])

    body = []
    short = {"Copenhagen": "Cph", "Oslo": "Oslo", "Stockholm": "Stockholm"}
    for source in CITIES:
        for target in CITIES:
            if source == target: continue
            for estimator in ESTIMATORS:
                rows = [one(data["transfer_performance"], source_city=source, target_city=target,
                            estimator=estimator, model=model) for model in MODELS]
                if len({row["n"] for row in rows}) != 1:
                    raise ValueError("Transfer model target samples differ")
                expected = int(one(data["city_sample_summary"], city=target)["prediction_n"])
                if int(rows[0]["n"]) != expected:
                    raise ValueError("Transfer target differs from its frozen common sample")
                body.append(" & ".join([short[source] + r" $\to$ " + short[target], estimator,
                                        *(number(row["rmse"]) for row in rows)]) + r" \\")
            if (source, target) != ("Stockholm", "Oslo"): body.append(r"\addlinespace")
    emit("transfer", "Source-only transfer RMSE for city-relative log asking prices.",
         "llrrrr", r"Source $\to$ target & Estimator & " + " & ".join(MODEL_TEX.values()),
         body, "Cph denotes Copenhagen--Frederiksberg. All four models use the same "
         "target observations in each direction. Source-only preprocessing and "
         "fitting are applied without target recalibration. Centring uses each "
         "city's frozen observed-price reference. Different directions have "
         "different target distributions; these scores do not rank intrinsic "
         "city transferability.", ["transfer_performance"])

    manifest = {
        "generator": "scripts/build_thesis_chapter_tables.py",
        "generator_sha256": digest(Path(__file__).read_bytes()),
        "source_catalog": str(CATALOG.relative_to(ROOT)),
        "source_catalog_sha256": CATALOG_SHA256,
        "inputs": inputs,
        "outputs": {name: digest(content.encode()) for name, content in outputs.items()},
        "models_refitted": False,
        "scientific_values_changed": False,
        "additional_descriptive_summary": summary_provenance,
    }
    outputs["manifest.json"] = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render()
    if args.check:
        different = [name for name, content in rendered.items()
                     if not (DEST / name).is_file() or (DEST / name).read_text() != content]
        if different: raise SystemExit(f"Generated manuscript artifacts differ: {different}")
        print(f"PASS: {len(rendered) - 1} tables and provenance match checksum-pinned aggregates")
    else:
        DEST.mkdir(exist_ok=True)
        for name, content in rendered.items(): (DEST / name).write_text(content)
        print(f"Rendered {len(rendered) - 1} manuscript tables; no scientific pipeline executed")


if __name__ == "__main__":
    main()
