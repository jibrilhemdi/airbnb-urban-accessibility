"""Render explanatory Methods assets from the executed design; never fit models."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def render():
    path = ROOT / "config/study/design.json"
    design = json.loads(path.read_text())
    expected = [["ME", "M0"], ["MW", "M0"], ["MEW", "M0"], ["MW", "ME"], ["MEW", "ME"]]
    if design["contrasts"] != expected or set(design["models"]) != {"M0", "ME", "MW", "MEW"}:
        raise ValueError("Review manuscript after any scientific specification change")
    labels = {"M0": r"$M_0$", "ME": r"$M_E$", "MW": r"$M_W$", "MEW": r"$M_{EW}$"}
    purposes = ["Euclidean contribution", "Walking contribution", "Joint contribution",
                "Replace Euclidean with walking", "Add walking to Euclidean"]
    body = [f"{labels[a]} & {labels[b]} & {purpose}" + r" \\" for (a, b), purpose in zip(expected, purposes)]
    table = "\n".join([
        "% Generated by scripts/build_thesis_methods_assets.py.",
        r"\begin{table}[H]\centering\small",
        r"\caption{Predictive model contrasts.}",
        r"\label{tab:method-contrasts}",
        r"\begin{tabular}{lll}\toprule",
        r"Candidate & Reference & Purpose \\", r"\midrule", *body,
        r"\bottomrule\end{tabular}\end{table}", "",
    ])
    boxes = ["Hold out one neighbourhood",
             "Compare settings on training data",
             "Train model; predict held-out listings"]
    content = []
    for i, message in enumerate(boxes, 1):
        if i > 1:
            content.append(r"\hfill$\longrightarrow$\hfill")
        content.append(r"\fcolorbox{KU}{white}{\begin{minipage}[c][1.6cm][c]{0.265\textwidth}"
                       r"\centering\small\SingleSpacing\textbf{Step " + str(i) + r"}\par "
                       + message + r"\end{minipage}}")
    figure = "\n".join([
        "% Generated by scripts/build_thesis_methods_assets.py; conceptual workflow, not results.",
        r"\begin{figure}[H]\centering", *content,
        r"\caption{XGBoost workflow, repeated for each neighbourhood.}",
        r"\label{fig:validation-workflow}\end{figure}", "",
    ])
    outputs = {"tables/method_contrasts.tex": table, "figures/validation_workflow.tex": figure}
    sources = ["config/study/design.json", "config/xgboost_candidates.json", "src/study/modeling.py",
               "src/study/validation.py", "src/study/accessibility.py", "src/reporting/study_results.py",
               "src/reporting/study_diagnostics.py", "src/pipeline/inference.py", "src/reporting/study_spatial.py"]
    manifest = {
        "generator": "scripts/build_thesis_methods_assets.py",
        "generator_sha256": digest(Path(__file__).read_bytes()),
        "inputs": {name: digest((ROOT / name).read_bytes()) for name in sources},
        "outputs": {name: digest(text.encode()) for name, text in outputs.items()},
        "kind": "Executed-design explanation; no new empirical estimates",
        "models_refitted": False, "database_writes": False,
    }
    outputs["tables/methods_assets_manifest.json"] = json.dumps(manifest, indent=2) + "\n"
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in render().items():
        path = ROOT / "thesis_report" / name
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise ValueError(f"Methods asset differs: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print("PASS: Methods comparison table, workflow and source hashes" if args.check else "Rendered Methods explanatory assets")


if __name__ == "__main__":
    main()
