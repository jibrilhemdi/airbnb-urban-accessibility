"""Render Chapter 4 tables and map from pinned exports and read-only PostGIS.

No SQL writes, source acquisition, model fitting or row-level exports.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = "reports/thesis_artifact_manifest.json"
PINS = {
    CATALOG: "29bf5b8334080cd4e8050a2d86dd415927aa3f051b38b7d9583996be3e007a52",
    "docs/analysis/context_audit.json": "896c75821992fa13318be5ef4a3bce0430bc93920020332c927e9a0acc67bdf6",
    "docs/analysis/sample_audit.json": "af1c5ea5360069cd2e7b82a41c426c342afedd876846a64b25ffa4598cac60cf",
}
CITIES = ("Copenhagen", "Oslo", "Stockholm")


def digest(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def render() -> dict[str, bytes]:
    inputs = {}

    def read(path: str, expected: str) -> bytes:
        raw = (ROOT / path).read_bytes()
        if digest(raw) != expected:
            raise ValueError(f"Evidence checksum changed: {path}")
        inputs[path] = expected
        return raw

    catalog = json.loads(read(CATALOG, PINS[CATALOG]))
    registered = {item["filename"]: item for item in catalog["items"]}

    def public(path: str) -> bytes:
        return read(path, registered[path]["sha256"])

    summary = list(csv.DictReader(io.StringIO(public("outputs/tables/city_sample_summary.csv").decode())))
    flow = list(csv.DictReader(io.StringIO(public("outputs/tables/sample_flow.csv").decode())))
    context = json.loads(read("docs/analysis/context_audit.json", PINS["docs/analysis/context_audit.json"]))
    samples = json.loads(read("docs/analysis/sample_audit.json", PINS["docs/analysis/sample_audit.json"]))
    by_city = {row["city"]: row for row in summary}
    if set(by_city) != set(CITIES) or len(summary) != 3:
        raise ValueError("Expected exactly three unique city summaries")
    from thesis_data_detail import read_details, compact_map
    map_data, missingness, detail_provenance = read_details()

    lines = []
    for label, stage in (
        ("Raw listings", "raw"),
        ("Eligible entire dwellings", "eligible_dwelling"),
        ("Observed positive asking price", "positive_observed_price"),
        ("Inside study area / price reference", "inside_study_area"),
        ("Common predictive sample", "common_prediction"),
        ("Complete-case association sample", "common_ols_association"),
    ):
        counts = []
        for city in CITIES:
            rows = [r for r in flow if r["city"] == city and r["stage"] == stage]
            if len(rows) != 1:
                raise ValueError(f"Missing/duplicate sample stage: {city}/{stage}")
            n = int(rows[0]["n"])
            audited = next(r["n"] for r in samples[city.lower()]["sample"]["sample_flow"] if r["stage"] == stage)
            if n != audited:
                raise ValueError("Sample flow disagrees with frozen audit")
            counts.append(f"{n:,}")
        lines.append(" & ".join([label, *counts]) + r" \\")
    lines.append(r"\addlinespace")
    for label, field in (("Predictor missingness (\\%)", "association_missing_percent"),
                         ("Validation neighbourhoods", "operational_neighbourhoods")):
        values = [f"{float(by_city[c][field]):.2f}" if field.endswith("percent") else str(int(by_city[c][field])) for c in CITIES]
        lines.append(" & ".join([label, *values]) + r" \\")

    def table(label: str, caption: str, spec: str, header: str, rows: list[str], note: str, flexible=False, compact=False) -> bytes:
        environment = "tabularx" if flexible else "tabular"
        opening = r"\begin{tabularx}{\textwidth}{" + spec + "}" if flexible else r"\begin{tabular}{" + spec + "}"
        return ("\n".join([
            "% Generated by scripts/build_thesis_data_assets.py; do not edit values.",
            r"\begin{table}[H]", r"\centering\small" + (r"\setlength{\tabcolsep}{4pt}" if compact else ""),
            r"\caption{" + caption + "}", r"\label{tab:" + label + "}",
            opening, r"\toprule", header + r" \\", r"\midrule", *rows,
            r"\bottomrule", r"\end{" + environment + "}", r"\par\smallskip",
            r"\begin{minipage}{\textwidth}\footnotesize", note,
            r"\end{minipage}", r"\end{table}", "",
        ])).encode()

    outputs = {"tables/data_samples.tex": table(
        "data-samples", "Listing selection and analytical samples.", "lrrr",
        "Stage & Copenhagen & Oslo & Stockholm", lines,
        "Source: frozen study sample-flow and city-summary exports from Inside Airbnb listings. "
        "Selection is sequential through the predictive sample; association complete cases "
        "are a subset. Predictor missingness is the share of predictive rows missing at "
        "least one required predictor. All four predictive models share rows and folds; "
        "no missing outcome is imputed.")}

    rows = []
    for city in CITIES:
        names = [r["group"] for r in map_data["districts"][city.lower()]]
        if len(names) != int(by_city[city]["operational_neighbourhoods"]):
            raise ValueError("District table count differs from final sample summary")
        rows.append(" & ".join([city, str(len(names)), "; ".join(names)]) + r" \\")
        if city != CITIES[-1]:
            rows.append(r"\addlinespace")
    outputs["tables/data_districts.tex"] = table(
        "data-districts", "Districts and other operational validation areas by city.",
        r"@{}>{\raggedright\arraybackslash}p{0.17\textwidth}r >{\raggedright\arraybackslash}X@{}",
        "City & Groups & District and area names", rows,
        r"Source: frozen Inside Airbnb geography \parencite{data_inside_cph2026,data_inside_oslo2026,data_inside_stockholm2026}. "
        "Names identify the study's validation groups, not a certification of current official districts. "
        "Copenhagen includes Frederiksberg; Oslo includes Sentrum and Marka. "
        "Stockholm's eleven groups combine fourteen provider labels.", flexible=True)

    periods = [u["reference_period"] for u in context["copenhagen"]["density_units"]]
    if not all("2026Q3" in p for p in periods):
        raise ValueError("Copenhagen density period changed")
    if {u["reference_period"] for u in context["oslo"]["density_units"]} != {"2026-01-01"}:
        raise ValueError("Oslo density period changed")
    if {u["reference_period"] for u in context["stockholm"]["density_units"]} != {"2025-12-31 population /2024-12-31 area table"}:
        raise ValueError("Stockholm density period changed")
    rows = [
        r"Inside Airbnb & 30 June 2026 catalogue batch; city-specific listings and neighbourhood polygons & Asking prices, listing controls and validation groups \\",
        r"OpenStreetMap & 30 June 2026, 23:59:59 UTC; study extent with a 2 km extraction buffer & Pedestrian routes, destinations and civic anchors \\",
        r"Copenhagen / Frederiksberg population & 2026Q3; KKBEF1 / FOLK1A with native district or municipal areas & Population density \\",
        r"Oslo population & 1 January 2026; BEF001 with native areas for 17 units & Population density \\",
        r"Stockholm population & 31 December 2025 population; 31 December 2024 published land-plus-water areas & Population density \\",
    ]
    outputs["tables/data_sources.tex"] = table(
        "data-sources", "Principal analytical sources and reference periods.",
        r"@{}>{\raggedright\arraybackslash}p{0.23\textwidth}"
        r">{\raggedright\arraybackslash}X >{\raggedright\arraybackslash}p{0.25\textwidth}@{}", "Input & Reference period and coverage & Analytical role", rows,
        r"Sources: \parencite{data_inside_cph2026,data_inside_oslo2026,data_inside_stockholm2026,data_osm_license,data_kkbef1,data_folk1a,data_oslo_bef001,data_stockholm_yearbook}. "
        "Reference periods describe the data, not download dates. Copenhagen's population "
        "reference is 1 July 2026. Area definitions and source vintages differ across cities.", flexible=True)
    order = ["Entire rental unit", "Entire condo", "Entire home", "Entire loft",
             "Entire townhouse", "Entire villa", "Other entire property types",
             "Entire dwelling: missing type", "Private room", "Shared room", "Hotel room", "Missing room type"]
    observed = set().union(*(set(rows) for rows in missingness.values()))
    if observed - set(order):
        raise ValueError("Unreviewed accommodation grouping")
    rows = []
    for category in [name for name in order if name in observed] + ["All original listings"]:
        values = []
        for city in CITIES:
            groups = missingness[city.lower()]
            if category == "All original listings":
                count = {key: sum(g[key] for g in groups.values()) for key in ("n", "missing_price", "missing_bedrooms")}
                if count["n"] != int(by_city[city]["raw_listings"]):
                    raise ValueError("Original source counts differ from final sample-flow export")
            else:
                # Exhaustive SQL source partition: an absent category has zero rows,
                # rather than an unobserved field whose value is being imputed.
                count = groups.get(category, {"n": 0, "missing_price": 0, "missing_bedrooms": 0})
            percentage = f"{100 * count['missing_price'] / count['n']:.1f}" if count["n"] else "--"
            values.extend([f"{count['n']:,}", f"{count['missing_price']:,}", percentage])
        if category == "All original listings":
            rows.append(r"\midrule")
        rows.append(" & ".join([category, *values]) + r" \\")
    outputs["tables/data_missingness.tex"] = table(
        "data-missingness", "Missing asking prices by accommodation type before sample selection.",
        "@{}lrrrrrrrrr@{}", r" & \multicolumn{3}{c}{Copenhagen} & \multicolumn{3}{c}{Oslo} & \multicolumn{3}{c}{Stockholm} \\ "
        r"Accommodation type & $N$ & Missing & \% & $N$ & Missing & \% & $N$ & Missing & \%", rows,
        "Source: original Inside Airbnb ingestions. $N$ is the listing count; Missing counts "
        "blank asking prices. Percentages are $100\\times\\mathrm{Missing}/N$ within city/type; "
        "a dash means $N=0$. Nonpositive prices are not missing. Room rows use source room "
        "type; other entire property types are pooled. Counts precede all sample filters.", compact=True)
    # Keep the completed original figure pinned and untouched; this is a distinct
    # manuscript rendering of the same authoritative geometry.
    public("outputs/figures/study_areas.png")
    outputs["figures/study_areas.png"] = compact_map(map_data)
    manifest = {
        "generator": "scripts/build_thesis_data_assets.py",
        "generator_sha256": digest(Path(__file__).read_bytes()),
        "inputs": inputs,
        "source_run_artifacts": {p: registered[p]["source_run_artifact"] for p in inputs if p in registered},
        "outputs": {p: digest(raw) for p, raw in outputs.items()},
        "read_only_details": detail_provenance,
        "map_presentation": {"north_arrow_label": "N", "north_direction": "projected grid north",
                             "layout": "compact; source attribution retained; frozen analytical boundaries unchanged",
                             "water": "Separate EU-Hydro 2006–2012 display overlay; no analytical use"},
        "model_refits": False,
        "database_writes": False,
        "note": "Presentation only; earlier audit statuses remain historical. Current association eligibility follows the 13 October 2026 amendment.",
    }
    outputs["tables/data_assets_manifest.json"] = (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode()
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = render()
    for name, raw in outputs.items():
        path = ROOT / "thesis_report" / name
        if args.check:
            if not path.is_file() or path.read_bytes() != raw:
                raise ValueError(f"Presentation artifact differs: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
    print("PASS: four Chapter 4 tables, compact map and provenance" if args.check else "Rendered Chapter 4 assets from pinned evidence")


if __name__ == "__main__":
    main()
